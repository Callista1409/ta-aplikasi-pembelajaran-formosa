export function curriculumHanziForms(value: string): string[] {
  return value.split(/[\/／]/u).map(word => word.replace(/[（(].*?[）)]/gu, '')
    .replace(/[\s…]/gu, '').trim()).filter(Boolean);
}

export function normalizeHanziOrder(value: string): string {
  return value.replace(/\s+/gu, '').trim();
}
