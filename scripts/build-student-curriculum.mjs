import ts from 'typescript';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

// Bundle the same pure curriculum functions used by Angular into the standalone API.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../src/app/core');
const output = resolve(root, '../../../admin-backend/student-curriculum');
const seen = new Set();
function emit(source) {
  if (seen.has(source)) return;
  seen.add(source);
  let code = ts.transpileModule(readFileSync(source, 'utf8'), {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 },
  }).outputText;
  code = code.replace(/(from\s+['"])(\.[^'"]+)(['"])/g, (_, before, specifier, after) => {
    emit(resolve(dirname(source), `${specifier}.ts`));
    return `${before}${specifier}.mjs${after}`;
  });
  const target = resolve(output, relative(root, source).replace(/\.ts$/, '.mjs'));
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, '// Generated by scripts/build-student-curriculum.mjs; edit the TypeScript source.\n' + code);
}
for (const entry of ['content/posttest-plan.ts', 'content/posttest-curriculum.ts', 'content/listening-question.ts']) emit(resolve(root, entry));
console.log(`Student API curriculum: ${seen.size} modules generated.`);
